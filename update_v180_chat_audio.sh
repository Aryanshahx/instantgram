#!/usr/bin/env bash
# =============================================================================
# Instantgram v1.8.0  -  Chats, audio in the preview, titles, volume fix
#   * Chats: new tab in the bottom bar. Open anyone's profile and tap Message, or search
#     for a username in Chats. Unread messages show a red dot.
#   * Create: audio section right under the preview (Post and Clips). In Clips you pick any
#     video or photo with one picker; a photo needs audio and gets a length of 5 to 30 s.
#   * A title is now required to publish a post or clip.
#   * Discover clips only play while Discover is on screen (not on other tabs).
#   * Clips: hold and slide up / down now changes the volume reliably; the 2x and volume
#     indicators have no background.
#   * New Firestore rules (chats). Publish them after this update.
# Run from the project root:   bash update_v180_chat_audio.sh
# =============================================================================
set -euo pipefail

EXPECTED_SHA256="7e632a86800f6ac6de6cdcad5cbe56ddad7a928f637bd006f5cab4e3e37174fe"

echo "==> Checking project..."
[ -f pubspec.yaml ] || { echo "ERROR: run this from the Flutter project root (pubspec.yaml not found)."; exit 1; }
[ -f lib/services/music_player.dart ] || { echo "ERROR: v1.7.0 is not installed. Run update_v170_music_inline.sh first."; exit 1; }
APP_NAME=$(grep -E '^name:' pubspec.yaml | head -1 | awk '{print $2}')
echo "    Dart package: $APP_NAME"

echo "==> Verifying the script (integrity check)..."
TMP_TGZ=$(mktemp /var/tmp/instantgram_payload.XXXXXX.tgz 2>/dev/null || mktemp /tmp/instantgram_payload.XXXXXX.tgz)
awk '/^__PAYLOAD__$/{f=1;next} f' "$0" | base64 -d > "$TMP_TGZ" 2>/dev/null || true
ACTUAL=$(sha256sum "$TMP_TGZ" | awk '{print $1}')
if [ "$ACTUAL" != "$EXPECTED_SHA256" ]; then
  echo "ERROR: the script file is incomplete or corrupted (checksum mismatch)."
  echo "       Download it again and retry."
  rm -f "$TMP_TGZ"; exit 1
fi

echo "==> Writing the updated files..."
tar xzf "$TMP_TGZ" -C .
rm -f "$TMP_TGZ"
grep -rl "package:instantgram/" lib test 2>/dev/null | xargs -r sed -i "s#package:instantgram/#package:${APP_NAME}/#" || true

echo ""
echo "Done. v1.8.0 is in place."
echo ""
echo "IMPORTANT (needed for Chats): publish the new Firestore rules."
echo "  Firebase console -> Build -> Firestore Database -> Rules tab"
echo "  Select everything, delete it, paste the full contents of  firebase/firestore.rules , press Publish."
echo ""
echo "Next:"
echo "  flutter clean && flutter pub get && dart analyze && flutter test"
echo '  git add -A && git commit -m "v1.8.0: chats, audio in preview, titles, volume fix" && git push'
exit 0
