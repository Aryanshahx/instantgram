#!/usr/bin/env bash
# =============================================================================
# Instantgram v1.5.0  -  Discover redesign, comments sheet, editing tools, faster clips
#   * Discover: author on top, photo/clip in its REAL proportions (square corners, nothing
#     drawn over it), heart + comment under it, "Add a comment...". No @, no video time.
#   * Comments slide up over the photo / over the playing clip (Discover and Clips).
#   * Heart-shaped like everywhere. Profile pictures are circles everywhere.
#   * Explore grid: real proportions, square corners.
#   * Create: square preview, photo editor (crop, rotate, flip, filters, brightness, contrast,
#     colour) and clip editor (trim, remove sound).
#   * Faster clips: the video index is moved to the front before upload (no re-encoding), so
#     new clips start playing straight away.
# Run from the project root:   bash update_v150_discover_editor.sh
# =============================================================================
set -euo pipefail

EXPECTED_SHA256="d743cf2e8bf7a57a88d953583c2f257c3fe7b02f85578b12b98edda9d87f5b8a"

echo "==> Checking project..."
[ -f pubspec.yaml ] || { echo "ERROR: run this from the Flutter project root (pubspec.yaml not found)."; exit 1; }
[ -f lib/widgets/reel_actions.dart ] || { echo "ERROR: v1.4.1 is not installed. Run update_v141_clips_create_ui.sh first."; exit 1; }
APP_NAME=$(grep -E '^name:' pubspec.yaml | head -1 | awk '{print $2}')
echo "    Dart package: $APP_NAME"

echo "==> Verifying the script (integrity check)..."
TMP_TGZ=$(mktemp /var/tmp/instantgram_payload.XXXXXX.tgz 2>/dev/null || mktemp /tmp/instantgram_payload.XXXXXX.tgz)
awk '/^__PAYLOAD__$/{f=1;next} f' "$0" | base64 -d > "$TMP_TGZ" 2>/dev/null || true
ACTUAL=$(sha256sum "$TMP_TGZ" | awk '{print $1}')
if [ "$ACTUAL" != "$EXPECTED_SHA256" ]; then
  echo "ERROR: the script file is incomplete or corrupted (checksum mismatch)."
  echo "       Download it again and retry."
  rm -f "$TMP_TGZ"; exit 1
fi

echo "==> Writing the updated files..."
tar xzf "$TMP_TGZ" -C .
rm -f "$TMP_TGZ"
sed -i "s#package:instantgram/#package:${APP_NAME}/#" test/*.dart

if ! grep -qE '^  image:' pubspec.yaml; then
  echo "==> Adding the 'image' package (photo editing)..."
  flutter pub add image
fi

echo ""
echo "Done. v1.5.0 is in place."
echo "Next:"
echo "  flutter clean && flutter pub get && dart analyze && flutter test"
echo '  git add -A && git commit -m "v1.5.0: Discover redesign, comments sheet, editing tools, faster clips" && git push'
exit 0
