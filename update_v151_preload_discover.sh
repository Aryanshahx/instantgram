#!/usr/bin/env bash
# =============================================================================
# Instantgram v1.5.1  -  Background preloading for Clips + Discover tweaks
#   * Clips: while a clip plays, the next 3 are downloaded to the phone in the background,
#     in pieces over several connections at once. They start instantly and never buffer.
#   * Discover: "InstantGram" title instead of the logo, share and save buttons under each
#     post, "Add a comment..." removed, clips show their whole frame (never cropped).
# Run from the project root:   bash update_v151_preload_discover.sh
# =============================================================================
set -euo pipefail

EXPECTED_SHA256="ce6a018d406554f9fce2178a1e2451899223da3727989d55c2b46c7d8681cb6c"

echo "==> Checking project..."
[ -f pubspec.yaml ] || { echo "ERROR: run this from the Flutter project root (pubspec.yaml not found)."; exit 1; }
[ -f lib/services/photo_edit.dart ] || { echo "ERROR: v1.5.0 is not installed. Run update_v150_discover_editor.sh first."; exit 1; }
APP_NAME=$(grep -E '^name:' pubspec.yaml | head -1 | awk '{print $2}')
echo "    Dart package: $APP_NAME"

echo "==> Verifying the script (integrity check)..."
TMP_TGZ=$(mktemp /var/tmp/instantgram_payload.XXXXXX.tgz 2>/dev/null || mktemp /tmp/instantgram_payload.XXXXXX.tgz)
awk '/^__PAYLOAD__$/{f=1;next} f' "$0" | base64 -d > "$TMP_TGZ" 2>/dev/null || true
ACTUAL=$(sha256sum "$TMP_TGZ" | awk '{print $1}')
if [ "$ACTUAL" != "$EXPECTED_SHA256" ]; then
  echo "ERROR: the script file is incomplete or corrupted (checksum mismatch)."
  echo "       Download it again and retry."
  rm -f "$TMP_TGZ"; exit 1
fi

echo "==> Writing the updated files..."
tar xzf "$TMP_TGZ" -C .
rm -f "$TMP_TGZ"
sed -i "s#package:instantgram/#package:${APP_NAME}/#" test/*.dart

echo ""
echo "Done. v1.5.1 is in place."
echo "Next:"
echo "  flutter clean && flutter pub get && dart analyze && flutter test"
echo '  git add -A && git commit -m "v1.5.1: clip preloading, Discover tweaks" && git push'
exit 0
