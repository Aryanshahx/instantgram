#!/usr/bin/env bash
# =============================================================================
# Instantgram v1.3.0  -  Cloudflare R2 media (no more Telegram, no more Raspberry Pi server)
#   * Photos, avatars, moments and videos are uploaded straight from the phone to a Cloudflare
#     R2 bucket (original quality, nothing compressed) and played from its public address.
#   * A tiny Cloudflare Worker checks the Firebase login and hands out one-time upload links.
#   * cloudflare/deploy.sh sets all of it up with one command.
#   * The Telegram media server is removed from this machine (service, Tailscale Funnel,
#     keys, Telegram session, folder).
#   * Clips preload the next video again (R2 is fast).
#   * Old posts, avatars and moments stored in Telegram can not be shown any more and are hidden.
# Run from the project root:   bash update_v130_cloudflare_r2.sh
# =============================================================================
set -euo pipefail

EXPECTED_SHA256="bb93246be8d813bfbc400fd1cb9c56f43dd24fd3759e3773bc3493253075fca1"

echo "==> Checking project..."
[ -f pubspec.yaml ] || { echo "ERROR: run this from the Flutter project root (pubspec.yaml not found)."; exit 1; }
[ -f lib/services/media_server.dart ] || { echo "ERROR: v1.2.x is not installed. Run the earlier update scripts first."; exit 1; }
APP_NAME=$(grep -E '^name:' pubspec.yaml | head -1 | awk '{print $2}')
echo "    Dart package: $APP_NAME"

echo "==> Verifying the script (integrity check)..."
TMP_TGZ=$(mktemp /var/tmp/instantgram_payload.XXXXXX.tgz 2>/dev/null || mktemp /tmp/instantgram_payload.XXXXXX.tgz)
awk '/^__PAYLOAD__$/{f=1;next} f' "$0" | base64 -d > "$TMP_TGZ" 2>/dev/null || true
ACTUAL=$(sha256sum "$TMP_TGZ" | awk '{print $1}')
if [ "$ACTUAL" != "$EXPECTED_SHA256" ]; then
  echo "ERROR: the script file is incomplete or corrupted (checksum mismatch)."
  echo "       Download it again and retry."
  rm -f "$TMP_TGZ"; exit 1
fi

# keep the Cloudflare addresses if they were already set (script run twice)
OLD_API=$(sed -n "s/^const String kMediaApiUrl = '\([^']*\)';.*/\1/p" lib/core/config.dart 2>/dev/null | head -1 || true)
OLD_PUB=$(sed -n "s/^const String kMediaPublicUrl = '\([^']*\)';.*/\1/p" lib/core/config.dart 2>/dev/null | head -1 || true)

echo "==> Writing the updated files..."
tar xzf "$TMP_TGZ" -C .
rm -f "$TMP_TGZ"
sed -i "s#package:instantgram/#package:${APP_NAME}/#" test/*.dart
chmod +x tools/set_media_url.sh tools/remove_pi_telegram.sh cloudflare/deploy.sh

if [ -n "${OLD_API:-}" ] && [ -n "${OLD_PUB:-}" ] && [[ "$OLD_API$OLD_PUB" != *CHANGE-ME* ]]; then
  bash tools/set_media_url.sh "$OLD_API" "$OLD_PUB" >/dev/null 2>&1 || true
  echo "    Kept your Cloudflare addresses."
fi

touch .gitignore
for line in "cloudflare/node_modules/" "cloudflare/.wrangler/" "cloudflare/.dev.vars"; do
  grep -qxF "$line" .gitignore || echo "$line" >> .gitignore
done

echo "==> flutter pub get"
flutter pub get

echo
echo "==> Removing the Telegram media server from this machine"
bash tools/remove_pi_telegram.sh || echo "The cleanup reported a problem. Read the lines above, then run: bash tools/remove_pi_telegram.sh"

cat <<'DONE'

 -----------------------------------------------------------------------------
 v1.3.0 installed.

 1) One-time Cloudflare setup (browser login + creating an access key):
      cd cloudflare && bash deploy.sh && cd ..

 2) Then:  flutter clean && flutter pub get && dart analyze && flutter test
    and commit + push for the new APK.

 Old posts, avatars and moments that were stored in Telegram are gone for good
 and are hidden by the app. New uploads go to Cloudflare R2.
 -----------------------------------------------------------------------------
DONE
exit 0

