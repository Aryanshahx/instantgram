#!/usr/bin/env bash
# =============================================================================
# Instantgram v1.4.1  -  Clips + Create screen cleanup, faster uploads
#   * Tapping any video (feed, profile, search) opens it in Clips, full screen.
#   * Clips: back button, plain icons (no circles), heart to like, clean layout.
#   * Create: step 1 = clean 9:16 preview (never stretched), step 2 = caption + Publish.
#   * Uploads: thumbnail goes up in parallel, photos show progress, MB/s is shown.
#   * signer/vercel.json: runs the signer in Mumbai (bom1), closer to you.
# Run from the project root:   bash update_v141_clips_create_ui.sh
# =============================================================================
set -euo pipefail

EXPECTED_SHA256="6ec607dfe027d88cf05f98cde125864f5af9886acffe854a492396563f8480d4"

echo "==> Checking project..."
[ -f pubspec.yaml ] || { echo "ERROR: run this from the Flutter project root (pubspec.yaml not found)."; exit 1; }
[ -f lib/screens/reels/reels_screen.dart ] && [ -d signer ] || { echo "ERROR: v1.4.0 is not installed. Run update_v140_tigris.sh first."; exit 1; }
APP_NAME=$(grep -E '^name:' pubspec.yaml | head -1 | awk '{print $2}')
echo "    Dart package: $APP_NAME"

echo "==> Verifying the script (integrity check)..."
TMP_TGZ=$(mktemp /var/tmp/instantgram_payload.XXXXXX.tgz 2>/dev/null || mktemp /tmp/instantgram_payload.XXXXXX.tgz)
awk '/^__PAYLOAD__$/{f=1;next} f' "$0" | base64 -d > "$TMP_TGZ" 2>/dev/null || true
ACTUAL=$(sha256sum "$TMP_TGZ" | awk '{print $1}')
if [ "$ACTUAL" != "$EXPECTED_SHA256" ]; then
  echo "ERROR: the script file is incomplete or corrupted (checksum mismatch)."
  echo "       Download it again and retry."
  rm -f "$TMP_TGZ"; exit 1
fi

echo "==> Writing the updated files..."
tar xzf "$TMP_TGZ" -C .
rm -f "$TMP_TGZ"
sed -i "s#package:instantgram/#package:${APP_NAME}/#" test/*.dart

# the old separate video screen is replaced by Clips
rm -f lib/screens/video/video_player_screen.dart
rmdir lib/screens/video 2>/dev/null || true

echo ""
echo "Done. v1.4.1 is in place."
echo "Next:"
echo "  flutter clean && flutter pub get && dart analyze && flutter test"
echo '  git add -A && git commit -m "v1.4.1: Clips and Create UI, faster uploads" && git push'
echo "The push also redeploys the Vercel signer (now in Mumbai)."
exit 0
