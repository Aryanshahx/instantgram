#!/usr/bin/env bash
# =============================================================================
# Instantgram v1.2.0  -  your own videos and photos, stored in Telegram
#   * Link videos are gone. Users upload clips (up to 60 s) from the gallery or camera.
#   * Clips play in a custom native player (reel layout, tap to pause, mute, progress line).
#   * Photos, avatars and moments are stored in your private Telegram channel too.
#   * media-server/ : the small server that sits between the app and Telegram.
#   * Firebase Storage is no longer used (no Blaze plan needed).
# Run from the project root:   bash update_v120_telegram_media.sh
# =============================================================================
set -euo pipefail

EXPECTED_SHA256="cc51965a3454d37cc364204783e99c2d1e8ae907ddfb19542e0034459f5d4d28"

echo "==> Checking project..."
[ -f pubspec.yaml ] || { echo "ERROR: run this from the Flutter project root (pubspec.yaml not found)."; exit 1; }
[ -f lib/screens/reels/reels_screen.dart ] || { echo "ERROR: v1.1.1 is not installed. Run update_v111_clips_tablet.sh first."; exit 1; }
APP_NAME=$(grep -E '^name:' pubspec.yaml | head -1 | awk '{print $2}')
echo "    Dart package: $APP_NAME"

echo "==> Verifying the script (integrity check)..."
TMP_TGZ=$(mktemp /var/tmp/instantgram_payload.XXXXXX.tgz 2>/dev/null || mktemp /tmp/instantgram_payload.XXXXXX.tgz)
awk '/^__PAYLOAD__$/{f=1;next} f' "$0" | base64 -d > "$TMP_TGZ" 2>/dev/null || true
ACTUAL=$(sha256sum "$TMP_TGZ" | awk '{print $1}')
if [ "$ACTUAL" != "$EXPECTED_SHA256" ]; then
  echo "ERROR: the script file is incomplete or corrupted (checksum mismatch)."
  echo "       Download it again and retry."
  rm -f "$TMP_TGZ"; exit 1
fi

echo "==> Removing the link-video packages..."
for pkg in youtube_player_iframe webview_flutter firebase_storage http; do
  if grep -qE "^  $pkg:" pubspec.yaml; then flutter pub remove "$pkg" || true; fi
done

echo "==> Adding packages (upload, video player, video compression)..."
flutter pub add dio video_player video_compress

echo "==> Removing obsolete files..."
rm -f lib/models/video_link.dart lib/widgets/video_embed.dart lib/services/storage_service.dart
rm -f firebase/storage.rules

echo "==> Writing the new files..."
tar xzf "$TMP_TGZ" -C .
rm -f "$TMP_TGZ"
sed -i "s#package:instantgram/#package:${APP_NAME}/#" test/*.dart
chmod +x media-server/install.sh tools/set_media_url.sh

echo "==> Keeping secrets out of git..."
touch .gitignore
for line in "media-server/.env" "media-server/.venv/" "media-server/*.session*" "__pycache__/" ".pytest_cache/"; do
  grep -qxF "$line" .gitignore || echo "$line" >> .gitignore
done

echo "==> flutter pub get"
flutter pub get

cat <<'DONE'

 -----------------------------------------------------------------------------
 v1.2.0 installed (the app side).

 STILL TO DO, once, on the Raspberry Pi (about 10 minutes):
   1. Read media-server/README.md (what to create in Telegram: bot, api keys, channel).
   2. Run:  bash media-server/install.sh
   3. Run the Tailscale Funnel command it prints at the end.
   4. Run:  bash tools/set_media_url.sh   (paste the https address), then commit and push.

 Then run:  flutter clean && flutter pub get && dart analyze && flutter test
 -----------------------------------------------------------------------------
DONE
echo
read -r -p "Do you already have the media server address? Paste it now, or press Enter to skip: " URL || URL=""
if [ -n "${URL:-}" ]; then bash tools/set_media_url.sh "$URL" || true; fi
exit 0

