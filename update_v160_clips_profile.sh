#!/usr/bin/env bash
# =============================================================================
# Instantgram v1.6.0  -  Faster clips, clips controls, profile sections and editing
#   * Clips: the clip on screen and the next 3 are downloaded to the phone over several
#     connections (smart wait, then stream); the first clips are warmed up after launch;
#     heavy uploads default to a smooth 720p copy.
#   * Clips screen: action buttons sit above the username, double tap = like, hold = 2x.
#   * Me screen: Posts and Clips sections.
#   * Edit profile: username, links, banner, profile picture, default silhouette picture.
#   * Firestore rules updated (fixes "Firestore blocked this request" on Save).
# Run from the project root:   bash update_v160_clips_profile.sh
# =============================================================================
set -euo pipefail

EXPECTED_SHA256="65d48d931efaca8c6e2500138c1ac37d46d477176039d99c7178b590fa21c52f"

echo "==> Checking project..."
[ -f pubspec.yaml ] || { echo "ERROR: run this from the Flutter project root (pubspec.yaml not found)."; exit 1; }
[ -f lib/services/clip_cache.dart ] || { echo "ERROR: v1.5.1 is not installed. Run update_v151_preload_discover.sh first."; exit 1; }
APP_NAME=$(grep -E '^name:' pubspec.yaml | head -1 | awk '{print $2}')
echo "    Dart package: $APP_NAME"

echo "==> Verifying the script (integrity check)..."
TMP_TGZ=$(mktemp /var/tmp/instantgram_payload.XXXXXX.tgz 2>/dev/null || mktemp /tmp/instantgram_payload.XXXXXX.tgz)
awk '/^__PAYLOAD__$/{f=1;next} f' "$0" | base64 -d > "$TMP_TGZ" 2>/dev/null || true
ACTUAL=$(sha256sum "$TMP_TGZ" | awk '{print $1}')
if [ "$ACTUAL" != "$EXPECTED_SHA256" ]; then
  echo "ERROR: the script file is incomplete or corrupted (checksum mismatch)."
  echo "       Download it again and retry."
  rm -f "$TMP_TGZ"; exit 1
fi

echo "==> Writing the updated files..."
tar xzf "$TMP_TGZ" -C .
rm -f "$TMP_TGZ"
sed -i "s#package:instantgram/#package:${APP_NAME}/#" test/*.dart

if ! grep -qE '^  url_launcher:' pubspec.yaml; then
  echo "==> Adding url_launcher (profile links)..."
  flutter pub add url_launcher
fi

echo ""
echo "Done. v1.6.0 is in place."
echo ""
echo "IMPORTANT (fixes Saved and username change): publish the new Firestore rules."
echo "  Firebase console -> Build -> Firestore Database -> Rules tab"
echo "  Select everything, delete it, paste the full contents of  firebase/firestore.rules , press Publish."
echo ""
echo "Next:"
echo "  flutter clean && flutter pub get && dart analyze && flutter test"
echo '  git add -A && git commit -m "v1.6.0: faster clips, profile sections, edit profile" && git push'
exit 0
