/// A country for the sign-up form (ISO 3166-1 alpha-2 code + English name).
class Country {
  const Country(this.code, this.name);
  final String code;
  final String name;

  /// The flag as an emoji (two regional-indicator letters).
  String get flag => String.fromCharCodes(
    code.toUpperCase().codeUnits.map((c) => 0x1F1E6 + c - 0x41),
  );
}

/// The country the phone is set up for (from the device language/region), or null.
Country? countryForCode(String? code) {
  if (code == null || code.isEmpty) return null;
  final c = code.toUpperCase();
  for (final k in kCountries) {
    if (k.code == c) return k;
  }
  return null;
}

/// Countries whose name or code contains [query] (all of them for an empty query).
List<Country> searchCountries(String query) {
  final q = query.trim().toLowerCase();
  if (q.isEmpty) return kCountries;
  return [
    for (final c in kCountries)
      if (c.name.toLowerCase().contains(q) || c.code.toLowerCase() == q) c,
  ];
}

