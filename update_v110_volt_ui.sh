set -euo pipefail

EXPECTED_SHA256="df326910634b67ac03b31e1b99adf1cef6f240f89bd506791d90c75e20593311"

echo "==> Checking project..."
[ -f pubspec.yaml ] || { echo "ERROR: run this from the Flutter project root (pubspec.yaml not found)."; exit 1; }
[ -f lib/services/post_service.dart ] || { echo "ERROR: v1 upgrade not installed yet (lib/services/post_service.dart missing). Run install_upgrade.sh first."; exit 1; }
APP_NAME=$(grep -E '^name:' pubspec.yaml | head -1 | awk '{print $2}')
echo "    Dart package: $APP_NAME"

echo "==> Verifying the script (integrity check)..."
TMP_TGZ=$(mktemp /var/tmp/instantgram_payload.XXXXXX.tgz 2>/dev/null || mktemp /tmp/instantgram_payload.XXXXXX.tgz)
awk '/^__PAYLOAD__$/{f=1;next} f' "$0" | base64 -d > "$TMP_TGZ" 2>/dev/null || true
ACTUAL=$(sha256sum "$TMP_TGZ" | awk '{print $1}')
if [ "$ACTUAL" != "$EXPECTED_SHA256" ]; then
  echo "ERROR: the script file is incomplete or corrupted (checksum mismatch)."
  echo "       Download it again and retry."
  rm -f "$TMP_TGZ"; exit 1
fi

echo "==> Adding dependency (masonry grid)..."
flutter pub add flutter_staggered_grid_view

echo "==> Writing the Volt UI files..."
tar xzf "$TMP_TGZ" -C .
rm -f "$TMP_TGZ"
sed -i "s#package:instantgram/#package:${APP_NAME}/#" test/*.dart

echo "==> flutter pub get"
flutter pub get

cat <<'DONE'

 -----------------------------------------------------------------------------
 Volt UI v1.1.0 installed.

 FIRST, fix "Permission denied": publish firebase/firestore.rules in the
 Firebase console (Firestore -> Rules -> paste -> Publish). Details are in
 FIREBASE_SETUP.md at the top.

 Then run:  flutter clean && flutter pub get && dart analyze && flutter test
 -----------------------------------------------------------------------------
DONE
exit 0

