#!/usr/bin/env bash
# =============================================================================
# Instantgram v1.4.0  -  Tigris media storage (replaces the Cloudflare plan)
#   * Photos, avatars, moments and videos go straight from the phone to a Tigris bucket
#     (original quality, nothing compressed) and play from its public address.
#   * A tiny signer service on Vercel (free, GitHub login) checks the Firebase login and hands
#     out one-time upload links. Folder: signer/
#   * signer/setup.sh guides you through the two websites and tests every step.
#   * The unused cloudflare/ folder is removed.
# Run from the project root:   bash update_v140_tigris.sh
# =============================================================================
set -euo pipefail

EXPECTED_SHA256="b303392b150de779ca15074f56c54bfff7f8d6eecc029759c5bb0ac98c3320e2"

echo "==> Checking project..."
[ -f pubspec.yaml ] || { echo "ERROR: run this from the Flutter project root (pubspec.yaml not found)."; exit 1; }
[ -f lib/services/media_server.dart ] || { echo "ERROR: v1.3.0 is not installed. Run the earlier update scripts first."; exit 1; }
APP_NAME=$(grep -E '^name:' pubspec.yaml | head -1 | awk '{print $2}')
echo "    Dart package: $APP_NAME"

echo "==> Verifying the script (integrity check)..."
TMP_TGZ=$(mktemp /var/tmp/instantgram_payload.XXXXXX.tgz 2>/dev/null || mktemp /tmp/instantgram_payload.XXXXXX.tgz)
awk '/^__PAYLOAD__$/{f=1;next} f' "$0" | base64 -d > "$TMP_TGZ" 2>/dev/null || true
ACTUAL=$(sha256sum "$TMP_TGZ" | awk '{print $1}')
if [ "$ACTUAL" != "$EXPECTED_SHA256" ]; then
  echo "ERROR: the script file is incomplete or corrupted (checksum mismatch)."
  echo "       Download it again and retry."
  rm -f "$TMP_TGZ"; exit 1
fi

# keep real addresses if they were already set (script run twice)
OLD_API=$(sed -n "s/^const String kMediaApiUrl = '\([^']*\)';.*/\1/p" lib/core/config.dart 2>/dev/null | head -1 || true)
OLD_PUB=$(sed -n "s/^const String kMediaPublicUrl = '\([^']*\)';.*/\1/p" lib/core/config.dart 2>/dev/null | head -1 || true)

echo "==> Writing the updated files..."
tar xzf "$TMP_TGZ" -C .
rm -f "$TMP_TGZ"
sed -i "s#package:instantgram/#package:${APP_NAME}/#" test/*.dart
chmod +x tools/set_media_url.sh tools/remove_pi_telegram.sh signer/setup.sh

if [ -n "${OLD_API:-}" ] && [ -n "${OLD_PUB:-}" ] && [[ "$OLD_API$OLD_PUB" != *CHANGE-ME* ]] \
   && [[ "$OLD_API$OLD_PUB" != *workers.dev* ]] && [[ "$OLD_API$OLD_PUB" != *r2.dev* ]]; then
  bash tools/set_media_url.sh "$OLD_API" "$OLD_PUB" >/dev/null 2>&1 || true
  echo "    Kept your media addresses."
fi

if [ -d cloudflare ]; then
  rm -rf cloudflare
  echo "    Removed the unused cloudflare/ folder."
fi
touch .gitignore
sed -i '/^cloudflare\//d' .gitignore
for line in "signer/node_modules/" "signer/.vercel/" "signer/.env*"; do
  grep -qxF "$line" .gitignore || echo "$line" >> .gitignore
done

echo "==> flutter pub get"
flutter pub get

cat <<'DONE'

 -----------------------------------------------------------------------------
 v1.4.0 installed.

 1) Check and publish the code (Vercel reads the signer folder from GitHub):
      flutter clean && flutter pub get && dart analyze && flutter test
      git add -A && git commit -m "v1.4.0: Tigris media storage" && git push

 2) One-time storage setup (two websites, the script tests every step):
      bash signer/setup.sh

 3) Commit and push the two new addresses it wrote, then install the new APK.
 -----------------------------------------------------------------------------
DONE
exit 0

