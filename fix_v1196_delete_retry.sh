#!/usr/bin/env bash
# InstantGram v1.19.6 fix: the delete tool retries on network drops instead of crashing,
# and redoes a half-finished first install by itself.
# Run from the project root:   bash fix_v1196_delete_retry.sh
set -euo pipefail
[ -f tools/admin/wipe.py ] || { echo "ERROR: run this in ~/IdeaProjects/instantgram (v1.19.6 needed)."; exit 1; }
T=$(mktemp)
awk '/^__PAYLOAD__/{f=1;next} /^#/{f=0} f' "$0" | sed 's/[[:cntrl:]]*$//' | base64 -d > "$T"
[ "$(sha256sum "$T" | cut -d' ' -f1)" = "66c5674ea9d7ed47327078cd6b130d2b6a499c83ec5a5548f59b167bea6931bc" ] || { echo "ERROR: download damaged - download it again."; rm -f "$T"; exit 1; }
tar xzf "$T" -C . && rm -f "$T"
chmod +x tools/delete_user.sh
echo "Done. Now run:  bash tools/delete_user.sh --leftovers --dry-run"
exit 0

