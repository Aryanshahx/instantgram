#!/usr/bin/env bash
# =============================================================================
# InstantGram v1.16.1  -  Privacy Policy and Terms of Use as Markdown (.md)
#   * docs/privacy.md and docs/terms.md (GitHub Pages turns them into
#     /privacy.html and /terms.html, the addresses the app and Play Console use).
#   * docs/_config.yml (theme), the old docs/privacy.html and docs/terms.html are removed.
# Run from the project root:   bash update_v1161_legal_md.sh
# =============================================================================
set -euo pipefail

EXPECTED_SHA256="8a97378878807808c54f06ade4105a46110aefbf44350474564b799d7eb894bd"

echo "==> Checking project..."
[ -f pubspec.yaml ] || { echo "ERROR: run this from the Flutter project root (pubspec.yaml not found)."; exit 1; }
[ -f lib/core/legal.dart ] || { echo "ERROR: v1.16.0 is not installed. Run update_v1160_signup_timeline_pins_qr.sh first."; exit 1; }
APP_NAME=$(grep -E '^name:' pubspec.yaml | head -1 | awk '{print $2}')

echo "==> Verifying the script (integrity check)..."
TMP_TGZ=$(mktemp /var/tmp/instantgram_payload.XXXXXX.tgz 2>/dev/null || mktemp /tmp/instantgram_payload.XXXXXX.tgz)
awk '/^__PAYLOAD__$/{f=1;next} f' "$0" | base64 -d > "$TMP_TGZ" 2>/dev/null || true
ACTUAL=$(sha256sum "$TMP_TGZ" | awk '{print $1}')
if [ "$ACTUAL" != "$EXPECTED_SHA256" ]; then
  echo "ERROR: the script file is incomplete or corrupted (checksum mismatch)."
  echo "       Download it again and retry."
  rm -f "$TMP_TGZ"; exit 1
fi

echo "==> Writing the files..."
tar xzf "$TMP_TGZ" -C .
rm -f "$TMP_TGZ"
rm -f docs/privacy.html docs/terms.html
grep -rl "package:instantgram/" lib test 2>/dev/null | xargs -r sed -i "s#package:instantgram/#package:${APP_NAME}/#" || true

echo ""
echo "Done. v1.16.1 is in place."
echo ""
echo "Play Console privacy policy address (after the push, with GitHub Pages on /docs):"
echo "  https://aryanshahx.github.io/instantgram/privacy.html"
exit 0
