#!/usr/bin/env bash
# InstantGram v1.15.1 - tests no longer depend on the Giphy key of the machine.
set -euo pipefail
EXPECTED_SHA256="169456bc96204ab2c75c79671c4cff374531eda23a28c38b2862cad11389d620"
